CREATE TABLE public.roles (
    rol_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cargo               VARCHAR(100) NOT NULL,
    descripcion         VARCHAR(150),
    fecha_creacion      TIMESTAMPTZ DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ,
    fecha_eliminacion   TIMESTAMPTZ
);

CREATE TABLE public.empleados (
    empleado_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres             VARCHAR(100) NOT NULL,
    apellidos           VARCHAR(100) NOT NULL,
    cedula              VARCHAR(25) NOT NULL,
    rol_id              INTEGER NOT NULL,
    fecha_nacimiento    DATE NOT NULL,
    fecha_contratacion  DATE NOT NULL,
    direccion           VARCHAR(150),
    pais                VARCHAR(50),
    telefono            VARCHAR(20),
    correo              VARCHAR(100),
    reportes            INTEGER,
    fecha_creacion      TIMESTAMPTZ DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ,
    fecha_eliminacion   TIMESTAMPTZ,

    CONSTRAINT fk_empleados_roles
        FOREIGN KEY (rol_id)
        REFERENCES public.roles (rol_id),

    CONSTRAINT fk_empleados_jefe
        FOREIGN KEY (reportes)
        REFERENCES public.empleados (empleado_id),

    CONSTRAINT uq_empleados_cedula
        UNIQUE (cedula),

    CONSTRAINT chk_empleados_correo
        CHECK (correo IS NULL OR correo LIKE '%_@%.%')
);

CREATE TABLE public.clientes (
    cliente_id            CHAR(5) PRIMARY KEY,
    tipo_cliente          VARCHAR(30) NOT NULL,
    numero_identificacion VARCHAR(50),
    nombre_empresa        VARCHAR(100) NOT NULL,
    nombre_contacto       VARCHAR(100),
    cargo_contacto        VARCHAR(50),
    direccion             VARCHAR(150),
    ciudad                VARCHAR(100),
    pais                  VARCHAR(50),
    telefono              VARCHAR(20),
    correo                VARCHAR(100),
    fecha_creacion        TIMESTAMPTZ DEFAULT NOW(),
    fecha_actualizacion   TIMESTAMPTZ,
    fecha_eliminacion     TIMESTAMPTZ,

    CONSTRAINT chk_clientes_tipo_cliente
        CHECK (tipo_cliente IN ('Persona Natural', 'Persona Jurídica')),

    CONSTRAINT chk_clientes_correo
        CHECK (correo IS NULL OR correo LIKE '%_@%.%')
);

