-- 5. AVALÚOS Y SERVICIOS
-- Se usa TIMESTAMP en avalúos para evitar error de generación no inmutable.
-- ============================================================

CREATE TABLE public.avaluos (
    avaluo_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id         INTEGER NOT NULL,
    descripcion         VARCHAR(200),
    monto_ejecutado     NUMERIC(18,2) NOT NULL,
    fecha_inicio        TIMESTAMP NOT NULL,
    fecha_fin           TIMESTAMP NOT NULL,

    tiempo_total_dias   INTEGER GENERATED ALWAYS AS (
        fecha_fin::DATE - fecha_inicio::DATE
    ) STORED,

    fecha_creacion      TIMESTAMP DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP,
    fecha_eliminacion   TIMESTAMP,

    CONSTRAINT fk_avaluos_proyectos
        FOREIGN KEY (proyecto_id)
        REFERENCES public.proyectos (proyecto_id),

    CONSTRAINT chk_avaluos_monto
        CHECK (monto_ejecutado >= 0),

    CONSTRAINT chk_avaluos_fechas
        CHECK (fecha_fin >= fecha_inicio)
);

CREATE TABLE public.servicios (
    servicio_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_servicio       VARCHAR(100) NOT NULL,
    descripcion           VARCHAR(200),
    total_costo_directo   NUMERIC(18,2) NOT NULL,
    total_costo_indirecto NUMERIC(18,2) NOT NULL,

    costo_venta           NUMERIC(18,2) GENERATED ALWAYS AS (
        total_costo_directo + total_costo_indirecto
    ) STORED,

    fecha_creacion        TIMESTAMPTZ DEFAULT NOW(),
    fecha_actualizacion   TIMESTAMPTZ,
    fecha_eliminacion     TIMESTAMPTZ,

    CONSTRAINT chk_servicios_total_costo_directo
        CHECK (total_costo_directo > 0),

    CONSTRAINT chk_servicios_total_costo_indirecto
        CHECK (total_costo_indirecto > 0)
);

CREATE TABLE public.costos_directos_servicios (
    costo_directo_id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servicio_id                     INTEGER NOT NULL,
    material_id                     INTEGER NOT NULL,
    cantidad_material               INTEGER NOT NULL,
    unidad_de_medida                VARCHAR(50) NOT NULL,
    precio_unitario                 NUMERIC(18,2) NOT NULL,

    costo_material                  NUMERIC(18,2) GENERATED ALWAYS AS (
        precio_unitario * cantidad_material
    ) STORED,

    mano_obra                       NUMERIC(18,2) GENERATED ALWAYS AS (
        (precio_unitario * cantidad_material) * 0.40
    ) STORED,

    equipos_transporte_herramientas NUMERIC(18,2) GENERATED ALWAYS AS (
        (precio_unitario * cantidad_material) * 0.10
    ) STORED,

    total_costo_directo             NUMERIC(18,2) GENERATED ALWAYS AS (
        (precio_unitario * cantidad_material) +
        ((precio_unitario * cantidad_material) * 0.40) +
        ((precio_unitario * cantidad_material) * 0.10)
    ) STORED,

    fecha_creacion                  TIMESTAMPTZ DEFAULT NOW(),
    fecha_actualizacion             TIMESTAMPTZ,
    fecha_eliminacion               TIMESTAMPTZ,

    CONSTRAINT fk_costos_directos_servicios
        FOREIGN KEY (servicio_id)
        REFERENCES public.servicios (servicio_id),

    CONSTRAINT fk_costos_directos_materiales
        FOREIGN KEY (material_id)
        REFERENCES public.materiales (material_id),

    CONSTRAINT chk_costos_directos_cantidad
        CHECK (cantidad_material > 0),

    CONSTRAINT chk_costos_directos_precio
        CHECK (precio_unitario > 0)
);

CREATE TABLE public.costos_indirectos_servicios (
    costo_indirecto_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servicio_id           INTEGER NOT NULL,
    costo_directo_id      INTEGER NOT NULL,
    total_costo_directo   NUMERIC(18,2) NOT NULL,

    administracion        NUMERIC(18,2) GENERATED ALWAYS AS (
        total_costo_directo * 0.05
    ) STORED,

    operacion             NUMERIC(18,2) GENERATED ALWAYS AS (
        total_costo_directo * 0.10
    ) STORED,

    utilidad              NUMERIC(18,2) GENERATED ALWAYS AS (
        total_costo_directo * 0.15
    ) STORED,

    precio_unitario       NUMERIC(18,2) GENERATED ALWAYS AS (
        (total_costo_directo * 0.05) +
        (total_costo_directo * 0.10) +
        (total_costo_directo * 0.15)
    ) STORED,

    total_costo_indirecto NUMERIC(18,2) GENERATED ALWAYS AS (
        (total_costo_directo * 0.05) +
        (total_costo_directo * 0.10) +
        (total_costo_directo * 0.15)
    ) STORED,

    fecha_creacion        TIMESTAMPTZ DEFAULT NOW(),
    fecha_actualizacion   TIMESTAMPTZ,
    fecha_eliminacion     TIMESTAMPTZ,

    CONSTRAINT fk_costos_indirectos_servicios
        FOREIGN KEY (servicio_id)
        REFERENCES public.servicios (servicio_id),

    CONSTRAINT fk_costos_indirectos_directos
        FOREIGN KEY (costo_directo_id)
        REFERENCES public.costos_directos_servicios (costo_directo_id),

    CONSTRAINT chk_costos_indirectos_total_directo
        CHECK (total_costo_directo > 0)
);

CREATE TABLE public.detalles_avaluos (
    detalle_avaluo_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avaluo_id           INTEGER NOT NULL,
    servicio_id         INTEGER NOT NULL,
    actividad           VARCHAR(100) NOT NULL,
    unidad_de_medida    VARCHAR(50) NOT NULL,
    cantidad            INTEGER NOT NULL,
    precio_unitario     NUMERIC(18,2) NOT NULL,

    costo_venta         NUMERIC(18,2) GENERATED ALWAYS AS (
        cantidad * precio_unitario
    ) STORED,

    iva                 NUMERIC(18,2) GENERATED ALWAYS AS (
        (cantidad * precio_unitario) * 0.15
    ) STORED,

    total_costo_venta   NUMERIC(18,2) GENERATED ALWAYS AS (
        (cantidad * precio_unitario) +
        ((cantidad * precio_unitario) * 0.15)
    ) STORED,

    observaciones       VARCHAR(200),
    fecha_creacion      TIMESTAMPTZ DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ,
    fecha_eliminacion   TIMESTAMPTZ,

    CONSTRAINT fk_detalles_avaluos_avaluos
        FOREIGN KEY (avaluo_id)
        REFERENCES public.avaluos (avaluo_id),

    CONSTRAINT fk_detalles_avaluos_servicios
        FOREIGN KEY (servicio_id)
        REFERENCES public.servicios (servicio_id),

    CONSTRAINT chk_detalles_avaluos_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT chk_detalles_avaluos_precio
        CHECK (precio_unitario >= 0)
);

